-- Esquema y datos de ejemplo para el organigrama
-- Codificación de dependencias: 10 posiciones (1 letra + 9 dígitos)

CREATE DATABASE IF NOT EXISTS milegajo CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE milegajo;

CREATE TABLE IF NOT EXISTS sv_dpnpdat0 (
    DPNDEP VARCHAR(10) NOT NULL,
    DPNDES VARCHAR(120) NOT NULL,
    PRIMARY KEY (DPNDEP)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

